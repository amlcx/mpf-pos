-- Money columns are integers in minor units. Timestamps are timestamptz.

create table stores (
  id              uuid primary key default gen_random_uuid(),
  code            text not null unique,
  name            text not null,
  currency_symbol text not null default '$',
  tax_rate_bps    integer not null default 0 check (tax_rate_bps between 0 and 10000),
  tax_included    boolean not null default true,
  created_at      timestamptz not null default now()
);

create table terminals (
  id           uuid primary key default gen_random_uuid(),
  store_id     uuid not null references stores,
  code         text not null,            -- ticket number prefix
  name         text not null,
  token_hash   text not null unique,     -- sha256 of the terminal's API token
  active       boolean not null default true,
  last_seen_at timestamptz,
  created_at   timestamptz not null default now(),
  unique (store_id, code)
);

create table users (
  id            uuid primary key default gen_random_uuid(),
  store_id      uuid references stores,  -- null: may work at every store
  username      text not null unique,
  name          text not null,
  role          text not null check (role in ('admin', 'cashier')),
  password_hash text not null,
  active        boolean not null default true,
  created_at    timestamptz not null default now()
);

-- The catalog is shared by all stores; stock is per store.
create table products (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  category    text not null default '',
  price_cents integer not null check (price_cents >= 0),
  track_stock boolean not null default true,
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- quantity may only go negative through an offline ('accept') order, and
-- every such case has a row in stock_conflicts.
create table stock (
  store_id   uuid not null references stores,
  product_id uuid not null references products,
  quantity   integer not null default 0,
  primary key (store_id, product_id)
);

create table orders (
  id             uuid primary key,       -- generated by the terminal
  store_id       uuid not null references stores,
  terminal_id    uuid not null references terminals,
  cashier_id     uuid not null references users,
  ticket_seq     integer not null check (ticket_seq > 0),
  ticket_number  text not null,
  status         text not null default 'completed' check (status in ('completed', 'voided')),
  stock_policy   text not null check (stock_policy in ('strict', 'accept')),
  tax_rate_bps   integer not null,
  tax_included   boolean not null,
  subtotal_cents integer not null check (subtotal_cents >= 0),
  tax_cents      integer not null check (tax_cents >= 0),
  total_cents    integer not null check (total_cents >= 0),
  created_at     timestamptz not null,   -- terminal clock at time of sale
  received_at    timestamptz not null default now(),
  voided_at      timestamptz,
  voided_by      uuid references users,
  void_reason    text,
  unique (terminal_id, ticket_seq)
);
create index orders_store_created_idx on orders (store_id, created_at);

create table order_lines (
  id               uuid primary key,
  order_id         uuid not null references orders,
  product_id       uuid not null references products,
  name             text not null,
  unit_price_cents integer not null check (unit_price_cents >= 0),
  quantity         integer not null check (quantity > 0),
  line_total_cents integer not null check (line_total_cents = unit_price_cents * quantity)
);
create index order_lines_order_idx on order_lines (order_id);

create table payments (
  id             uuid primary key,
  order_id       uuid not null references orders,
  method         text not null check (method in ('cash', 'digital')),
  amount_cents   integer not null check (amount_cents > 0),
  tendered_cents integer,
  check (method = 'cash' or tendered_cents is null),
  check (tendered_cents is null or tendered_cents >= amount_cents)
);
create index payments_order_idx on payments (order_id);

-- Ledger: every change to stock.quantity has exactly one row here.
create table stock_movements (
  id         uuid primary key default gen_random_uuid(),
  store_id   uuid not null references stores,
  product_id uuid not null references products,
  delta      integer not null check (delta <> 0),
  reason     text not null check (reason in ('sale', 'void', 'adjustment')),
  order_id   uuid references orders,
  user_id    uuid references users,
  created_at timestamptz not null default now()
);
create index stock_movements_order_idx on stock_movements (order_id);

-- An offline sale that sold more than the store had. An admin resolves it.
create table stock_conflicts (
  id          uuid primary key default gen_random_uuid(),
  store_id    uuid not null references stores,
  order_id    uuid not null references orders,
  product_id  uuid not null references products,
  shortfall   integer not null check (shortfall > 0),
  created_at  timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references users,
  resolution  text,
  unique (order_id, product_id)
);
